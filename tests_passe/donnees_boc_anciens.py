VIDE = {'', '-', '—', 'n.d.', 'n/d', 'nd', 'ND', 'NC', 'SP'}

def nombre(x):
    x = x.strip()
    if x in VIDE: return ''
    return x.replace(' ', '').replace(' ', '').replace('%', '').replace(',', '.')

def date_iso(x):
    x = x.strip()
    if x in VIDE: return ''
    j, m, a = x.replace('.', '').split('-')
    a = int(a); a = 2000 + a if a < 50 else 1900 + a
    return f"{a:04d}-{MOIS[m]:02d}-{int(j):02d}"

def convertir():
    out = {}
    for d, s in RAW.items():
        lignes = []
        for l in s['data'].strip().splitlines():
            p = (l.split(';') + [''] * 6)[:6]
            cours = p[1].strip() if p[1].strip() in ('SP', 'NC') else nombre(p[1])
            lignes.append(';'.join([p[0].strip(), cours, nombre(p[2]), date_iso(p[3]), nombre(p[4]), nombre(p[5])]))
        rdt = s['rdt']
        if rdt is None:  # rendement moyen absent du bulletin : mediane des rendements publies
            vals = sorted(float(x.split(';')[4]) for x in lignes if x.split(';')[4] and 0 < float(x.split(';')[4]) < 25)
            rdt = round(vals[len(vals) // 2], 2)
        out[d] = dict(composite=s['composite'], per=s['per'], rdt=rdt, data='\n'.join(lignes))
    return out
